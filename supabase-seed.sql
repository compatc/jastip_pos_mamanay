-- Make sure all tables exist first
CREATE TABLE IF NOT EXISTS customers (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT DEFAULT '',
  address TEXT DEFAULT '',
  category TEXT DEFAULT 'pelanggan',
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
  id TEXT PRIMARY KEY,
  customer_id TEXT NOT NULL,
  user_id TEXT NOT NULL,
  status TEXT DEFAULT 'new',
  total REAL DEFAULT 0,
  paid_total REAL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  order_type TEXT DEFAULT 'penjualan',
  payment_type TEXT DEFAULT 'tf',
  ongkir REAL DEFAULT 0,
  notes TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS order_items (
  id TEXT PRIMARY KEY,
  order_id TEXT NOT NULL,
  product_name TEXT NOT NULL,
  price REAL DEFAULT 0,
  quantity INTEGER DEFAULT 1,
  paid_value REAL DEFAULT 0,
  status TEXT DEFAULT 'new',
  discount REAL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS products (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  cost_price REAL DEFAULT 0,
  sell_price REAL DEFAULT 0,
  stock INTEGER DEFAULT 0,
  unit TEXT DEFAULT 'PCS',
  image TEXT DEFAULT '',
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS stock_movements (
  id TEXT PRIMARY KEY,
  product_id TEXT NOT NULL,
  date TEXT NOT NULL,
  transaction_type TEXT NOT NULL,
  invoice_no INTEGER DEFAULT 0,
  party_name TEXT DEFAULT '',
  qty INTEGER DEFAULT 0,
  qty_after INTEGER DEFAULT 0,
  unit TEXT DEFAULT 'SET',
  created_at TEXT NOT NULL
);

